"""Regenerate src/validation/simready_vocab.py from a checkout of NVIDIA/simready-foundation.

    python -I tests/build_simready_vocab.py PATH/TO/simready-foundation

Reads the six dataset taxonomies and the affordance vocabulary of the SimReady Foundation core tier and writes
them as one small Python module, so the X3D checks need no JSON file at run time and no network. The commit of
the checkout is written into the module; tests/usd_rules.json pins the same commit.
"""
from __future__ import annotations

import ast
import json
import re
import subprocess
import sys
from pathlib import Path

CORE = "nv_core/tiers/simready_foundation_tier_core/simready/foundation/tier_core/rules_and_reqs"
SLUGS = ("ade20k", "cityscapes", "coco", "imagenet_1k", "pascal_voc", "sunrgbd")
_WS = re.compile(r"[\s_\-]+")


def normalize(value: str) -> str:
    return _WS.sub(" ", value.strip().lower())


def main(repo: Path) -> None:
    commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    vocab, sources = {}, {}
    for slug in SLUGS:
        data = json.loads((repo / CORE / "dataset_taxonomies" / "taxonomies" / f"{slug}.json").read_text(encoding="utf-8"))
        names, alias = [], {}
        for entry in data["labels"]:
            name = entry.get("name")
            if not name or name in names:
                continue
            names.append(name)
        canon = set(names)
        for entry in data["labels"]:
            name = entry.get("name")
            for other in [name, entry.get("display_name"), *(entry.get("aliases") or [])]:
                if other and other not in canon:
                    alias.setdefault(normalize(other), name)
            alias.setdefault(normalize(name), name)
        alias = {k: v for k, v in alias.items() if k != v}       # an exact name needs no alias row
        vocab[slug] = {"title": data.get("taxonomy_name") or slug, "names": names, "alias": dict(sorted(alias.items()))}
        sources[slug] = data.get("source_url") or ""
    ns = {}
    src = (repo / CORE / "physics_bodies" / "object_affordances" / "validation.py").read_text(encoding="utf-8")
    for node in ast.parse(src).body:                         # read the two literal tables; the file is never executed
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in (
                "_ALLOWED_AFFORDANCES", "_STATE_AFFORDANCES"):
            lit = node.value.args[0] if isinstance(node.value, ast.Call) else node.value
            ns[node.targets[0].id] = ast.literal_eval(lit)
    vocab["affordance"] = {"title": "SimReady object affordances", "names": sorted(ns["_ALLOWED_AFFORDANCES"]), "alias": {}}
    vocab["affordance_state"] = {"title": "SimReady object affordance states", "names": sorted(ns["_STATE_AFFORDANCES"]), "alias": {}}
    out = ['"""Closed label vocabularies for the X3D SimReady profile checks (simready_checks.py).',
           "",
           "GENERATED by tests/build_simready_vocab.py; do not edit by hand.",
           f"Source: NVIDIA/simready-foundation @ {commit} (Apache-2.0), core tier:",
           "  rules_and_reqs/dataset_taxonomies/taxonomies/*.json and rules_and_reqs/physics_bodies/object_affordances/validation.py",
           "The class names themselves come from the public datasets named in each file there:"]
    for slug in SLUGS:
        out.append(f"  {slug}: {vocab[slug]['title']}" + (f" ({sources[slug]})" if sources[slug] else ""))
    out += ["Only label names are kept (no images, no annotations). If a rights holder wants a list removed, open an issue",
            "on this repository and it is taken out at once.",
            '"""',
            f"SOURCE_COMMIT = {commit!r}",
            "VOCAB = " + json.dumps(vocab, ensure_ascii=True, separators=(",", ":"), sort_keys=True),
            ""]
    dest = Path(__file__).resolve().parent.parent / "src" / "validation" / "simready_vocab.py"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(dest, dest.stat().st_size, "bytes;", {k: len(v["names"]) for k, v in vocab.items()})


if __name__ == "__main__":
    main(Path(sys.argv[1]))
